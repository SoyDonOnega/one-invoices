#!/usr/bin/env python3
"""Build the AEAT model 349 import file (500-position records) and a summary by EU operator from the register.

Usage:
    python3 scripts/aeat349.py <config.json> <year> <quarter 1-4> [--id 349xxxxxxxxxx] [--force]

Writes <output_dir>/349/<year>-T<q>.txt and <year>-T<q>.md, or nothing when the quarter has no EU operations.
Operation keys: I (EU services received: kind eu-services), S (services to an EU client: issued row whose client
tax ID has an EU prefix other than ES and no VAT). Rectification records are not built. Never files anything.
--id: 13-digit declaration number starting with 349; default 349 + year + quarter + zeros. Standard library only.
"""
import json
import sys
from decimal import Decimal
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import aeat303  # noqa: E402
import register  # noqa: E402
from aeat303 import GenError, in_quarter, render  # noqa: E402

EOL = "\r\n"  # between records; to be confirmed by a file exported from the AEAT site


def operations(issued: list[dict], received: list[dict], year: int, q: int) -> dict[tuple[str, str], dict]:
    """(tax ID, key) -> {name, base, rows}, summed over the quarter."""
    ops: dict[tuple[str, str], dict] = {}

    def put(tax_id, name, key, row):
        if tax_id[:2] not in register.EU_PREFIXES - {"ES"}:
            raise GenError(f"{row['number']}: tax ID {tax_id!r} must start with an EU country code")
        o = ops.setdefault((tax_id, key), {"name": name, "base": Decimal(0), "rows": []})
        o["base"] += row["base"]
        o["rows"].append(f"{row['number']} ({row['date']})")

    for r in received:
        if r["kind"] == "eu-services" and in_quarter(r["date"], year, q):
            put(r["supplier_tax_id"], r["supplier"], "I", r)
    for r in issued:
        if r["client_tax_id"][:2] in register.EU_PREFIXES - {"ES"} and not r["vat"] and in_quarter(r["date"], year, q):
            put(r["client_tax_id"], r["client"], "S", r)
    return ops


def build(design: dict, cfg: dict, year: int, q: int, ops: dict, decl_id: str) -> str:
    p = design["pages"]
    period = f"{q}T"
    head = render(p["type1"], {3: year, 4: cfg["nif"].zfill(9), 5: cfg["name"], 7: cfg["phone"], 8: cfg["contact_name"],
                               9: decl_id, 13: period, 14: len(ops), 15: sum((o["base"] for o in ops.values()), Decimal(0))})
    lines = [head]
    for (tax_id, key), o in sorted(ops.items()):
        lines.append(render(p["type2"], {3: year, 4: cfg["nif"].zfill(9), 6: tax_id[:2], 7: tax_id[2:], 8: o["name"],
                                         9: key, 10: o["base"]}))
    return EOL.join(lines) + EOL


def summary(design: dict, year: int, q: int, ops: dict, decl_id: str) -> str:
    lines = [f"# Model 349 — {year} Q{q}", "",
             f"Record design: `{design['source_file']}`. Declaration number: `{decl_id}`.",
             "Generated by one-invoices. Not filed: import the `.txt` in the AEAT site, review it and file it there.", "",
             "| Operator tax ID | Name | Key | Base (EUR) | Register rows |", "|---|---|---|---|---|"]
    for (tax_id, key), o in sorted(ops.items()):
        lines.append(f"| {tax_id} | {o['name']} | {key} | {o['base']:.2f} | {', '.join(o['rows'])} |")
    total = sum((o["base"] for o in ops.values()), Decimal(0))
    lines += ["", f"Operators: {len(ops)}. Total: {total:.2f} EUR."]
    return "\n".join(lines) + "\n"


def main(argv: list[str]) -> int:
    args, opts, it = [], {}, iter(argv)
    for a in it:
        if a == "--force":
            opts[a] = "1"
        elif a == "--id":
            opts[a] = next(it, "")
        else:
            args.append(a)
    if len(args) != 3:
        print(__doc__.strip(), file=sys.stderr)
        return 2
    try:
        cfg = json.loads(Path(args[0]).expanduser().read_text(encoding="utf-8"))
        year, q = int(args[1]), int(args[2])
        if q not in (1, 2, 3, 4):
            raise GenError("quarter must be 1-4")
        missing = [k for k in ("nif", "name", "phone", "contact_name", "register_note", "output_dir") if not cfg.get(k)]
        if missing:
            raise GenError(f"config is missing: {', '.join(missing)}")
        decl_id = opts.get("--id") or f"349{year}{q}".ljust(13, "0")
        if len(decl_id) != 13 or not decl_id.isdigit() or not decl_id.startswith("349"):
            raise GenError(f"--id must be 13 digits starting with 349: {decl_id!r}")
        design = aeat303.load_design(year, "349")
        note = Path(cfg["register_note"]).expanduser()
        ops = operations(register.read(note, "issued"), register.read(note, "received"), year, q)
        if not ops:
            print(f"nothing to declare: no EU operations in {year} Q{q}; no file written")
            return 0
        text = build(design, cfg, year, q, ops, decl_id)
        out = Path(cfg["output_dir"]).expanduser() / "349"
        txt, md = out / f"{year}-T{q}.txt", out / f"{year}-T{q}.md"
        if txt.exists() and "--force" not in opts:
            raise GenError(f"{txt} already exists — run again with --force to overwrite")
        out.mkdir(parents=True, exist_ok=True)
        txt.write_text(text, encoding="latin-1", newline="")
        md.write_text(summary(design, year, q, ops, decl_id), encoding="utf-8")
        print(f"{txt}\n{md}\noperators: {len(ops)}")
    except (GenError, register.RegisterError, FileNotFoundError, json.JSONDecodeError, ValueError) as e:
        print(f"error: {e}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
